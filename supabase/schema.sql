-- 12 characters from 31 that can't be mixed up (no i, l, o, 0 or 1), from
-- the server's strong random source (gen_random_uuid), skipping the uuid's
-- fixed bits and bytes 248-255 so every character is equally likely.
create function private.make_family_code() returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  alphabet constant text := 'abcdefghjkmnpqrstuvwxyz23456789';
  result text := '';
  bytes bytea;
  b int;
begin
  while length(result) < 12 loop
    bytes := uuid_send(gen_random_uuid());
    for i in 0..15 loop
      continue when i in (6, 8);
      b := get_byte(bytes, i);
      continue when b >= 248;
      result := result || substr(alphabet, (b % 31) + 1, 1);
      exit when length(result) >= 12;
    end loop;
  end loop;
  return result;
end;
$$;

revoke execute on function private.make_family_code() from public, anon, authenticated;

insert into private.family_code (id, code) values (true, private.make_family_code());

-- How codes are compared everywhere: lowercase, no spaces at the ends, and
-- any run of spaces inside made a single space (migration 009).
create function private.clean_family_code(code text) returns text
language sql
immutable
set search_path = ''
as $$
  select btrim(regexp_replace(lower(coalesce(code, '')), '[[:space:]]+', ' ', 'g'));
$$;

revoke execute on function private.clean_family_code(text) from public, anon, authenticated;

