#variable_conflict use_column
declare
  clean_name text := trim(left(trim(regexp_replace(coalesce(start_handover.name, ''), '[[:space:][:cntrl:]]+', ' ', 'g')), 40));
  t uuid;
begin
  if auth.uid() is null or not public.is_allowed() then
